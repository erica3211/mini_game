/**
 * 자모 수가 정확히 5개이고, 자모를 다시 조합했을 때 원래 단어로 돌아오는
 * (= 미리보기가 정답을 그대로 보여줄 수 있는) 단어만 사용한다.
 */
export const HANGUL_WORDS = WORD_CANDIDATES.filter((word) => {
  const jamo = decomposeWord(word)
  return jamo.length === HANGUL_LENGTH && assembleJamo(jamo) === word
})
